import mongoose, { Schema, Document, Types } from 'mongoose';
export interface IIncident extends Document {
  shiftId: string;
  reportedBy: Types.ObjectId; // User who reported the incident
  reportedAgainst?: Types.ObjectId; // Optional: Who the incident is against (e.g., a worker)
  title: string; // Brief title or summary
  description: string; // Detailed description
  severity: 'LOW' | 'MEDIUM' | 'HIGH'; // Severity of the incident
  urlLinks?: string[]; // Optional reference URLs
  status: 'OPEN' | 'IN_REVIEW' | 'RESOLVED' | 'REJECTED';
  resolutionNote?: string; // Admin or Participant resolution comment
  resolvedBy?: Types.ObjectId; // Admin or Participant who handled the incident
  resolvedAt?: Date; // Timestamp when resolved
  createdAt: Date;
  updatedAt: Date;
}

const incidentSchema = new Schema<IIncident>(
  {
    shiftId: {
      type: String,
      ref: 'Shift',
      required: true,
      validate: {
        // Use an existence check instead of strict regex to avoid rejecting valid shiftIds
        // that may have been generated by the Shift creation routine.
        validator: async function (value: string) {
          try {
            // Use `exists` for a lighter-weight check
            const exists = await mongoose.model('Shift').exists({ shiftId: value });
            return !!exists;
          } catch (err) {
            // If the validate check throws for any reason, fail validation to be safe
            return false;
          }
        },
        message: 'Shift does not exist. Incident cannot be created.',
      },
    },
    reportedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    reportedAgainst: {
      type: Schema.Types.ObjectId,
      ref: 'User',
    },
    title: {
      type: String,
      required: true,
      trim: true,
    },
    description: {
      type: String,
      required: true,
    },
    severity: {
      type: String,
      enum: ['LOW', 'MEDIUM', 'HIGH'],
      default: 'LOW',
    },
    urlLinks: {
      type: [String],
      validate: {
        validator: function (arr: string[]) {
          return arr.every((link) => /^https?:\/\/\S+$/.test(link));
        },
        message: 'One or more URLs are invalid',
      },
    },
    status: {
      type: String,
      enum: ['OPEN', 'IN_REVIEW', 'RESOLVED', 'REJECTED'],
      default: 'OPEN',
    },
    resolutionNote: {
      type: String,
    },
    resolvedBy: {
      type: Schema.Types.ObjectId,
      ref: 'User',
    },
    resolvedAt: {
      type: Date,
    },
  },
  { timestamps: true },
);

incidentSchema.index({ shiftId: 1, status: 1, severity: 1, reportedBy: 1, reportedAgainst: 1 });

const Incident = mongoose.model<IIncident>('Incident', incidentSchema);
export default Incident;
